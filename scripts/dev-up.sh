#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Bring the EPCC development stack up: build the image, start PostgreSQL and
# the app, wait for the first boot to finish, print how to log in.
#
#   scripts/dev-up.sh              start (or rebuild if compose.yaml changed)
#   scripts/dev-up.sh --rebuild    force a rebuild of the app image
#   scripts/dev-up.sh --reset      destroy ALL data first, then start clean
#   scripts/dev-up.sh --logs       tail the app log after the stack is healthy
#
# The first boot is the slow one: Composer installs ~16,500 files, npm builds
# the Vite assets, and the demo fixture is migrated and seeded. Expect a few
# minutes. Every later boot is seconds, because vendor/ and node_modules/ live
# in named volumes and the database in db-data.
# ---------------------------------------------------------------------------
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

say()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m!!  %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[1;31mxx  %s\033[0m\n' "$*" >&2; exit 1; }
# Print this file's header comment as the usage text. Reading it out of the
# source is deliberate: a hand-copied usage block drifts away from the options
# actually implemented, and nobody notices until it has lied for a month.
# `-+` rather than `-\{10,\}`: mawk, the awk on a default Debian/Ubuntu host,
# does not support interval expressions, and an unmatched pattern here silently
# prints the whole script instead of the usage block.
usage() { awk 'NR>2 && /^# -+$/ {exit} NR>2 {print}' "$0"; }

REBUILD=0 RESET=0 LOGS=0
for arg in "$@"; do
    case "$arg" in
        --rebuild) REBUILD=1 ;;
        --reset)   RESET=1 ;;
        --logs)    LOGS=1 ;;
        -h|--help)     usage; exit 0 ;;
        *) die "unknown option: $arg (try --help)" ;;
    esac
done

# ------------------------------------------------------------- prerequisites --
command -v docker >/dev/null 2>&1 \
    || die "docker is not installed. See docs/DEVELOPMENT-ENVIRONMENT.md §1."
docker info >/dev/null 2>&1 \
    || die "the Docker daemon is not reachable. Start Docker Desktop / the docker service."

if docker compose version >/dev/null 2>&1; then
    COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
    COMPOSE=(docker-compose)
else
    die "neither 'docker compose' nor 'docker-compose' is available (Compose v2 plugin missing)"
fi

# ----------------------------------------------------------- host uid/gid ----
# Files written through the bind mount (app/.env, storage/logs, public/build)
# come out owned by whatever uid the container runs as. Left at root, the next
# host-side `composer install` or editor save dies with EACCES. On Linux we
# therefore hand the container the real uid; on macOS and Windows Docker
# Desktop already maps ownership, and forcing a uid there breaks it instead.
#
# compose.yaml reads these from ./.env automatically, which is gitignored.
if [ ! -f .env ]; then
    if [ "$(uname -s)" = "Linux" ]; then
        say "Creating ./.env with the host uid/gid ($(id -u):$(id -g))"
        {
            echo "# Generated by scripts/dev-up.sh - development only, gitignored."
            echo "# EPCC_UID/EPCC_GID make container-written files owned by you."
            echo "EPCC_UID=$(id -u)"
            echo "EPCC_GID=$(id -g)"
            echo "#APP_PORT=8000"
            echo "#DB_FORWARD_PORT=5433"
        } > .env
    else
        say "Creating ./.env ($(uname -s): ownership is already mapped by Docker Desktop)"
        {
            echo "# Generated by scripts/dev-up.sh - development only, gitignored."
            echo "#APP_PORT=8000"
            echo "#DB_FORWARD_PORT=5433"
        } > .env
    fi
fi

# Load only the two keys this script needs. Sourcing ./.env would execute
# whatever else a developer put in there.
EPCC_UID="${EPCC_UID:-$(sed -n 's/^EPCC_UID=//p' .env 2>/dev/null | tail -1 || true)}"
EPCC_GID="${EPCC_GID:-$(sed -n 's/^EPCC_GID=//p' .env 2>/dev/null | tail -1 || true)}"
APP_PORT="${APP_PORT:-$(sed -n 's/^APP_PORT=//p' .env 2>/dev/null | tail -1 || true)}"
APP_PORT="${APP_PORT:-8000}"
DB_FORWARD_PORT="${DB_FORWARD_PORT:-$(sed -n 's/^DB_FORWARD_PORT=//p' .env 2>/dev/null | tail -1 || true)}"
DB_FORWARD_PORT="${DB_FORWARD_PORT:-5433}"

# ------------------------------------------------------------------- reset ----
if [ "$RESET" -eq 1 ]; then
    say "--reset: destroying containers AND volumes (database, vendor, node_modules)"
    "${COMPOSE[@]}" down --volumes --remove-orphans
fi

# -------------------------------------------------------------------- build ---
if [ "$REBUILD" -eq 1 ]; then
    say "Building the app image (--no-cache)"
    "${COMPOSE[@]}" build --no-cache app
else
    say "Building the app image (cached)"
    "${COMPOSE[@]}" build app
fi

# --------------------------------------------------------------------- up -----
say "Starting the stack"
"${COMPOSE[@]}" up -d --remove-orphans

# -------------------------------------------------------------------- wait ----
# `up -d` returns as soon as the containers are created; the entrypoint is still
# installing dependencies and seeding. Reporting success here would send a
# developer to a URL that is about to 500, so wait for the healthcheck instead.
say "Waiting for the first boot to finish (dependencies, migrations, seed, assets)"
container_id=$("${COMPOSE[@]}" ps -q app)
[ -n "$container_id" ] || die "the app container did not start; see: ${COMPOSE[*]} logs app"

status="starting"
for _ in $(seq 1 120); do
    status=$(docker inspect -f \
        '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
        "$container_id" 2>/dev/null || echo unknown)
    case "$status" in
        healthy) break ;;
        unhealthy|exited|dead)
            say "App container is '$status'. Last 40 log lines:"
            "${COMPOSE[@]}" logs --tail=40 app
            die "boot failed"
            ;;
    esac
    sleep 3
done

if [ "$status" != "healthy" ]; then
    warn "not healthy yet after ~6 minutes (status: $status) - the first boot can be slow."
    warn "Keep watching with: ${COMPOSE[*]} logs -f app"
else
    say "Stack is healthy"
fi

cat <<EOF

  EPCC Platform development stack

    App:      http://localhost:${APP_PORT}
    Login:    karimi@nioc.example / password
    Admin:    http://localhost:${APP_PORT}/admin
    Postgres: 127.0.0.1:${DB_FORWARD_PORT} -> db:5432 (user epcc / epcc_dev, databases epcc + epcc_test)

    Tests:    scripts/dev-test.sh
    Re-seed:  scripts/dev-seed.sh
    Stop:     scripts/dev-down.sh          (keeps data)
              scripts/dev-down.sh --volumes (destroys it)
    Shell:    ${COMPOSE[*]} exec app bash
    Logs:     ${COMPOSE[*]} logs -f app

EOF

if [ "$LOGS" -eq 1 ]; then
    "${COMPOSE[@]}" logs -f app
fi
