/**
 * Unit preferences and canonical values (ADR-014).
 *
 * Three things:
 *
 * 1. `project_piping_config.unit_preferences` - the project default, set once
 *    by the employer at setup.
 * 2. `users.unit_preferences` - a personal override, so an international
 *    contractor can read psi while the employer reads barg off the same rows.
 * 3. `piping_lines.*_kpa` / `*_c` - the canonical value beside every entered
 *    value.
 *
 * WHY THE CANONICAL COLUMNS EXIST AT ALL
 * --------------------------------------
 * The entered value and unit are the source of truth: they are what the
 * engineer typed and what the drawing says. But a query like "every line above
 * 10 barg" cannot be written against a value/unit pair without joining a unit
 * table and multiplying in SQL - which is unindexable and has to be repeated
 * at every call site.
 *
 * So the canonical value is stored alongside, generated by the application on
 * write. It is derived data. If the two ever disagree, the entered pair wins
 * and the canonical is recomputed - never the other way round.
 *
 * WHY NOT A GENERATED COLUMN
 * --------------------------
 * PostgreSQL generated columns must be IMMUTABLE, and the conversion factors
 * live in a versioned JSON pack that can gain units in a later revision. A
 * generated column would freeze today's factor table into the schema and make
 * a pack revision a migration. The application owns the conversion; the column
 * just stores the result.
 */
